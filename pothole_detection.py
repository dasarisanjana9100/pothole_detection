import os
import cv2
from ultralytics import YOLO
from IPython.display import display, Video

# Step 1: Load the trained model
model_path = "/content/pothole_project/pothole_detector/weights/best.pt"
video_path = "/content/road_video.mp4"

if not os.path.exists(model_path):
    print("Trained model not found. Check the model path.")

elif not os.path.exists(video_path):
    print("Video not found. Please download the video first.")

else:
    model = YOLO(model_path)

    # Step 2: Open the video
    cap = cv2.VideoCapture(video_path)

    fps = cap.get(cv2.CAP_PROP_FPS)
    width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

    if not cap.isOpened() or fps <= 0:
        print("Unable to open the video.")

    else:
        # Step 3: Create output video
        output_path = "/content/pothole_detection_output.mp4"

        fourcc = cv2.VideoWriter_fourcc(*"mp4v")
        out = cv2.VideoWriter(
            output_path, fourcc, fps, (width, height)
        )

        total_detections = 0
        frames_processed = 0

        # Step 4: Detect objects in each frame
        while True:
            ret, frame = cap.read()

            if not ret:
                break

            results = model.predict(
                source=frame,
                conf=0.25,
                verbose=False
            )

            annotated_frame = results[0].plot()
            out.write(annotated_frame)

            total_detections += len(results[0].boxes)
            frames_processed += 1

            if frames_processed % 100 == 0:
                print("Frames processed:", frames_processed)

        # Step 5: Release resources
        cap.release()
        out.release()

        print("\nVideo processing completed!")
        print("Total frames processed:", frames_processed)
        print("Total detections across frames:", total_detections)
        print("Output saved at:", output_path)

        # Step 6: Display the processed video
        if frames_processed > 0:
            display(Video(output_path, embed=True))

